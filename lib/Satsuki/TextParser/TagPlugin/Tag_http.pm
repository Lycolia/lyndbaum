package Satsuki::TextParser::TagPlugin::Tag_http;
################################################################################
# ■基本処理
################################################################################
#-------------------------------------------------------------------------------
# ●コンストラクタ
#-------------------------------------------------------------------------------
sub new {
	my $class = shift;	# 読み捨て
	my $ROBJ  = shift;	# 読み捨て
	my $tags = shift;

	#---begin_plugin_info
	$tags->{http}  ->{data} = \&http;
	$tags->{https} ->{data} = \&http;
	$tags->{ftp}   ->{data} = \&http;
	$tags->{mailto}->{data} = \&mailto;
	#---end

	return ;
}
################################################################################
# ■タグ処理ルーチン
################################################################################
#-------------------------------------------------------------------------------
# ●http記法
#-------------------------------------------------------------------------------
sub http {
	my ($pobj, $tag, $cmd, $ary) = @_;

	# URL取り出し
	my $url2 = shift(@$ary);
	if ($ary->[0] =~ /^#/) {
		$url2 .= shift(@$ary);
	}
	# URIエンコード
	$pobj->encode_uri($url2);
	$cmd =~ s/\W//g;
	my $url = $url2;
	if (substr($url2,0,2) eq '//') { $url = $cmd . ':' . $url2; }
	# 属性/リンク名
	my $attr = $pobj->make_attr($ary, $tag);
	my $name = $pobj->make_name($ary, $url);

	# 中の a を取り除く
	$name =~ s!<a(?:\s+[\w\-]+\s*=\s*"[^\"]*"|\s+[\w\-])*\s*>(.*)</a>!$1!i;

	return "<a href=\"$url\"$attr>$name</a>";
}
#---------------------------------------------------------------------
# ●mailto記法
#---------------------------------------------------------------------
sub mailto {
	my ($pobj, $tag, $cmd, $ary) = @_;

	my $mail = shift(@$ary);
	$mail =~ s/\"\'/'%' . unpack('H2',$1)/eg;
	$mail = 'mailto:' . $mail;
	my $attr = $pobj->make_attr($ary, $tag);
	my $name = $pobj->make_name($ary, $mail);

	return "<a href=\"$mail\"$attr>$name</a>";
}


1;
